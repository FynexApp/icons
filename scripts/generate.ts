/**
 * Generates every file derived from `src/catalog.ts`:
 * - `src/icons/index.ts`, the barrel of the icon files;
 * - `registry.json`, the shadcn registry (one core item, one item per icon);
 * - the icon table of `README.md`, between its markers.
 *
 *   node scripts/generate.ts          writes the files
 *   node scripts/generate.ts --check  fails if one of them is out of date
 *
 * Runs on Node 22.18 or later (type stripping), with no build step.
 * `REGISTRY_URL` overrides the hosting URL of the registry, for a local test.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { ICON_CATALOG, ICON_FAMILIES, type IconFamily } from '../src/catalog.ts'

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

/** Where `public/r/` is served. Placeholder until the GitHub Pages site exists. */
export const DEFAULT_REGISTRY_URL = 'https://fynexapp.github.io/icons/r'

/** Where the files land in a shadcn project, under its `components` alias. */
export const INSTALL_DIR = '@components/fynex-icons'

/** The core files, in dependency order. */
export const CORE_FILES = [
  'icon-context.ts',
  'icon-trigger.ts',
  'icon-trigger-scope.tsx',
  'animate-icon.tsx',
  'motions.ts',
  'make-icon.tsx',
]

export const CORE_ITEM = 'icons-core'

const FAMILY_ORDER = Object.keys(ICON_FAMILIES) as IconFamily[]

const byFamily = (family: IconFamily) => ICON_CATALOG.filter((entry) => entry.family === family)

/** `ChartColumnIncreasing` becomes `Chart Column Increasing`. */
const title = (name: string) => name.replace(/(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Za-z])(?=[0-9])/g, ' ')

export function renderBarrel(): string {
  const lines = ['// Generated by scripts/generate.ts from src/catalog.ts. Do not edit by hand.', '']
  for (const family of FAMILY_ORDER) {
    lines.push(`// ${ICON_FAMILIES[family].label}`)
    for (const entry of byFamily(family)) lines.push(`export * from './${entry.slug}'`)
    lines.push('')
  }
  return lines.join('\n')
}

export function renderRegistry(registryUrl = DEFAULT_REGISTRY_URL): string {
  const core = {
    name: CORE_ITEM,
    type: 'registry:component',
    title: 'Fynex icons core',
    description:
      'The icon factory, the motion grammar and the triggers (AnimateIcon, IconTrigger, useIconTrigger) shared by every Fynex icon.',
    author: 'Fynex <https://fynexapp.com>',
    dependencies: ['motion'],
    files: CORE_FILES.map((file) => ({
      path: `src/${file}`,
      type: 'registry:component',
      target: `${INSTALL_DIR}/${file}`,
    })),
  }
  const icons = FAMILY_ORDER.flatMap((family) =>
    byFamily(family).map((entry) => ({
      name: entry.slug,
      type: 'registry:component',
      title: title(entry.name),
      description: `${entry.motion}.`,
      author: 'Fynex <https://fynexapp.com>',
      dependencies: ['motion'],
      registryDependencies: [`${registryUrl}/${CORE_ITEM}.json`],
      files: [
        {
          path: `src/icons/${entry.slug}.tsx`,
          type: 'registry:component',
          target: `${INSTALL_DIR}/icons/${entry.slug}.tsx`,
        },
      ],
      categories: [family],
      meta: { component: entry.name, aliases: entry.aliases },
    })),
  )
  const registry = {
    $schema: 'https://ui.shadcn.com/schema/registry.json',
    name: 'fynex-icons',
    homepage: 'https://github.com/FynexApp/icons',
    items: [core, ...icons],
  }
  return `${JSON.stringify(registry, null, 2)}\n`
}

export const README_START = '<!-- icons:start -->'
export const README_END = '<!-- icons:end -->'

export function renderIconTable(): string {
  const out: string[] = [README_START, '', `${ICON_CATALOG.length} icons in ${FAMILY_ORDER.length} families.`, '']
  for (const family of FAMILY_ORDER) {
    const entries = byFamily(family)
    out.push(`### ${ICON_FAMILIES[family].label} (${entries.length})`, '', ICON_FAMILIES[family].grammar, '')
    out.push('| Component | shadcn item | On hover | lucide aliases |', '| --- | --- | --- | --- |')
    for (const entry of entries) {
      const aliases = entry.aliases.map((alias) => `\`${alias}\``).join(', ')
      out.push(`| \`${entry.name}\` | \`${entry.slug}\` | ${entry.motion} | ${aliases} |`)
    }
    out.push('')
  }
  out.push(README_END)
  return out.join('\n')
}

export function renderReadme(current: string): string {
  const start = current.indexOf(README_START)
  const end = current.indexOf(README_END)
  if (start < 0 || end < start) throw new Error(`README.md has no ${README_START} ... ${README_END} markers`)
  return current.slice(0, start) + renderIconTable() + current.slice(end + README_END.length)
}

/** Every generated file, by path relative to the repository root. */
export function generatedFiles(): Record<string, string> {
  const files: Record<string, string> = {
    'src/icons/index.ts': renderBarrel(),
    'registry.json': renderRegistry(process.env.REGISTRY_URL ?? DEFAULT_REGISTRY_URL),
  }
  const readme = path.join(ROOT, 'README.md')
  if (fs.existsSync(readme)) files['README.md'] = renderReadme(fs.readFileSync(readme, 'utf8'))
  return files
}

function main() {
  const check = process.argv.includes('--check')
  const stale: string[] = []
  for (const [file, content] of Object.entries(generatedFiles())) {
    const target = path.join(ROOT, file)
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
    if (current === content) continue
    if (check) stale.push(file)
    else fs.writeFileSync(target, content)
  }
  if (stale.length > 0) {
    console.error(`Out of date, run \`npm run generate\`: ${stale.join(', ')}`)
    process.exit(1)
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
